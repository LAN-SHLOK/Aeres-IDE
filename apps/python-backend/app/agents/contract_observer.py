"""Contract Observer — records live function I/O and generates snapshot tests for 25+ languages."""

import json
import ast
import hashlib
import re
from pathlib import Path
from typing import Any, List, Dict
from datetime import datetime

# Contract observations are stored per function per session
# Structure: { "filePath:functionName": [{ inputs, output, timestamp, isEdgeCase, inputHash }] }
observations: Dict[str, List] = {}


def record_observation(file_path: str, function_name: str, inputs: list, output: Any, error: str = None):
    """Record a live function call observation from a run/debug session."""
    import os
    norm_path = os.path.normpath(file_path).lower().replace('\\', '/')
    key = f"{norm_path}:{function_name}"
    if key not in observations:
        observations[key] = []

    # Detect edge cases: None/null inputs, empty collections, zero values, error outputs
    is_edge = (
        any(v is None for v in inputs) or
        any(v == [] or v == {} or v == "" for v in inputs) or
        any(v == 0 for v in inputs) or
        error is not None
    )

    try:
        input_str = json.dumps(inputs, default=str)
    except Exception:
        input_str = str(inputs)

    input_hash = hashlib.md5(input_str.encode()).hexdigest()[:8]

    # Deduplicate: don't store same inputs twice
    existing_hashes = {o['inputHash'] for o in observations[key]}
    if input_hash not in existing_hashes:
        observations[key].append({
            "inputs": inputs,
            "output": output,
            "error": error,
            "timestamp": datetime.utcnow().isoformat(),
            "isEdgeCase": is_edge,
            "inputHash": input_hash
        })


def generate_snapshot_tests(file_path: str, function_name: str, language: str) -> str:
    """Generate idiomatic, compilable snapshot tests for a function in the given language."""
    # Normalize the key for lookup
    import os
    norm_path = os.path.normpath(file_path).lower().replace('\\', '/')
    key = f"{norm_path}:{function_name}"
    obs_list = observations.get(key, [])

    stem = Path(file_path).stem

    # Route to language-specific generator
    generators = {
        'python': _generate_python_tests,
        'javascript': _generate_js_tests,
        'typescript': _generate_ts_tests,
        'go': _generate_go_tests,
        'rust': _generate_rust_tests,
        'java': _generate_java_tests,
        'kotlin': _generate_kotlin_tests,
        'csharp': _generate_csharp_tests,
        'cpp': _generate_cpp_tests,
        'c': _generate_c_tests,
        'ruby': _generate_ruby_tests,
        'php': _generate_php_tests,
        'dart': _generate_dart_tests,
        'swift': _generate_swift_tests,
        'lua': _generate_lua_tests,
        'elixir': _generate_elixir_tests,
        'haskell': _generate_haskell_tests,
        'scala': _generate_scala_tests,
        'r': _generate_r_tests,
        'perl': _generate_perl_tests,
        'shell': _generate_shell_tests,
        'powershell': _generate_powershell_tests,
        'nim': _generate_nim_tests,
        'zig': _generate_zig_tests,
        'fsharp': _generate_fsharp_tests,
        'clojure': _generate_clojure_tests,
        'erlang': _generate_erlang_tests,
        'scala': _generate_scala_tests,
    }

    gen = generators.get(language)
    if gen:
        return gen(function_name, file_path, obs_list)

    # Default JS fallback
    return _generate_js_tests(function_name, file_path, obs_list)


