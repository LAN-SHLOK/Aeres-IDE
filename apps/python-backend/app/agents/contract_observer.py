def _generate_python_tests(fn: str, file_path: str, obs: List) -> str:
    mod_name = Path(file_path).stem
    class_name = ''.join(w.capitalize() for w in fn.split('_'))
    if not obs:
        return f"""# Auto-generated by Aeres IDE — Contract Snapshot Tests
import pytest
from {mod_name} import {fn}  # adjust import path as needed

class Test{class_name}Contract:
    \"\"\"Snapshot tests for {fn}() — generated from static analysis.\"\"\"

    def test_basic_call(self):
        \"\"\"Verify {fn} returns a non-None result with default args.\"\"\"
        result = {fn}()
        assert result is not None

    def test_edge_case_none_input(self):
        \"\"\"Edge case: passing None should be handled gracefully.\"\"\"
        try:
            result = {fn}(None)
        except (TypeError, ValueError):
            pass  # Expected — function rejects None

    def test_edge_case_empty(self):
        \"\"\"Edge case: passing empty values.\"\"\"
        try:
            result = {fn}("")
        except (TypeError, ValueError):
            pass  # Expected

if __name__ == "__main__":
    import sys
    sys.exit(pytest.main([__file__]))
"""
    lines = [
        f"# Auto-generated by Aeres IDE — Contract Snapshot Tests",
        f"# Generated from {len(obs)} observed calls to {fn}()",
        f"import pytest",
        f"from {mod_name} import {fn}  # adjust path as needed",
        f"",
        f"class Test{class_name}Contract:",
    ]
    for i, o in enumerate(obs[:20]):
        label = f"edge_case_{i}" if o['isEdgeCase'] else f"observed_call_{i}"
        args = ', '.join(repr(v) for v in o['inputs'])
        if o['error']:
            lines += [f"", f"    def test_{label}(self):", f"        # Observed error: {o['error']}", f"        with pytest.raises(Exception):", f"            {fn}({args})"]
        else:
            lines += [f"", f"    def test_{label}(self):", f"        result = {fn}({args})", f"        assert result == {repr(o['output'])}"]
    return '\n'.join(lines)


